/*
 * mobilenet_v1_meminfo - MobileNetV1 (uint8, 224x224x3) Ethos-U benchmark.
 *
 * The model is linked into flash, copied once into a PSRAM slab (the NPU cannot
 * read flash directly) and then invoked with an all-zero 224x224x3 input. Only
 * the Invoke() cost is measured. Every round appends the same test report the
 * face demo used to print: model size, shared arena / fast-scratch placement
 * and the invoke timings.
 */
/* os/os.h does NOT wrap its declarations in `extern "C"`, so it must be pulled
 * in here - BEFORE any other header - to keep C linkage. If another header
 * includes it first, the include guard is set with C++ linkage and APIs such as
 * rtos_create_thread get mangled, which fails at link time with undefined
 * references. */
extern "C" {
#include <os/os.h>
}

#include "bk_private/bk_init.h"

#include <components/system.h>
#include <components/bk_frame_buffer.h>
#include <components/log.h>
#include <common/bk_err.h>
#include <driver/aon_rtc.h>
#include <stdint.h>
#include <string.h>

#include "media_service.h"
#include "AvdkMultiModel.h"

/* BK_LOG* takes a non-const char *tag, and C++ forbids binding a string
 * literal to char *, so keep the tag in a writable array. */
static char TAG[] = "model_bench";
#define LOGI(...) BK_LOGI(TAG, ##__VA_ARGS__)
#define LOGE(...) BK_LOGE(TAG, ##__VA_ARGS__)

/* MobileNetV1 vela model, generated by the Vela compiler: uint8 input
 * [1,224,224,3] -> uint8 output [1,1001]. A single Ethos-U custom op. */
extern "C" {
extern const unsigned char mobilenet_v1_1_0_224_quant_vela_tflite[];
extern const unsigned int mobilenet_v1_1_0_224_quant_vela_tflite_len;
}

#define MODEL_INPUT_W            224
#define MODEL_INPUT_H            224
#define MODEL_INPUT_C            3
#define MODEL_INPUT_BYTES        (MODEL_INPUT_W * MODEL_INPUT_H * MODEL_INPUT_C)

/* Same layout as projects/tflite_micro/datasheet_model_test: 1 MB tensor arena
 * in PSRAM, 448 KB Ethos-U fast scratch in HSRAM, model copied from flash into
 * an uncoded PSRAM slab. */
#define MODEL_ARENA_SIZE         (1024 * 1024)
#define MODEL_SCRATCH_SIZE       (448 * 1024)

/* How many Invoke() runs make up one round (and one report). */
#define MODEL_RUNS_PER_ROUND     3

#define MODEL_TASK_STACK_SIZE    (1024 * 8)

static AvdkMultiModel *s_model = NULL;
static tflite::MicroInterpreter *s_interpreter = NULL;

/* Per-round counters used by the report. */
static uint32_t s_round_runs;
static uint32_t s_round_failures;
static uint32_t s_round_invoke_sum_us;
static uint32_t s_round_invoke_min_us;
static uint32_t s_round_invoke_max_us;

static const char *model_mem_type_name(avdk_nn_mem_type_t type)
{
    switch (type) {
    case AVDK_NN_MEM_TYPE_HSRAM:
        return "HSRAM";
    case AVDK_NN_MEM_TYPE_SRAM:
        return "SRAM";
    case AVDK_NN_MEM_TYPE_PSRAM_HEAP:
        return "PSRAM heap";
    case AVDK_NN_MEM_TYPE_PSRAM_SLAB:
        return "PSRAM slab";
    case AVDK_NN_MEM_TYPE_PSRAM_SLAB_UNCODED:
        return "PSRAM slab (uncoded)";
    case AVDK_NN_MEM_TYPE_FALSH:
        return "flash";
    default:
        return "unknown";
    }
}

static void model_round_stats_reset(void)
{
    s_round_runs = 0;
    s_round_failures = 0;
    s_round_invoke_sum_us = 0;
    s_round_invoke_min_us = 0;
    s_round_invoke_max_us = 0;
}

static void model_print_round_report(int round)
{
    uint32_t model_bytes = s_model->modelDataSize();
    uint32_t arena_capacity = AvdkMultiModel::sharedArenaSize();
    uint32_t scratch_bytes = AvdkMultiModel::fastScratchSize();
    uint32_t arena_used = (s_interpreter != NULL) ?
                          (uint32_t)s_interpreter->arena_used_bytes() : 0;
    uint32_t invoke_avg_us = s_round_runs ? (s_round_invoke_sum_us / s_round_runs) : 0;
    bool pass = (s_round_runs == MODEL_RUNS_PER_ROUND) && (s_round_failures == 0);

    LOGI("\r\n");
    LOGI("================ ROUND %d TEST REPORT ================\r\n", round);
    LOGI("[System]\r\n");
    LOGI("  chip        : BK7259 (Cortex-M55 + Ethos-U65)\r\n");
    LOGI("  firmware    : mobilenet_benchmark  built %s %s\r\n", __DATE__, __TIME__);
    LOGI("  round       : %d\r\n", round);

    LOGI("[Models]\r\n");
    LOGI("  %-16s %7.1f KB  input %dx%dx%d\r\n", "MobileNetV1",
         (float)model_bytes / 1024.0f, MODEL_INPUT_W, MODEL_INPUT_H, MODEL_INPUT_C);

    LOGI("[Memory map]\r\n");
    LOGI("  model         : %7.1f KB  linked in flash -> PSRAM slab (uncoded)\r\n",
         (float)model_bytes / 1024.0f);
    LOGI("  shared arena  : %7.1f KB  %s, tensor arena used by Invoke\r\n",
         (float)arena_capacity / 1024.0f,
         model_mem_type_name(AvdkMultiModel::sharedArenaType()));
    LOGI("  fast scratch  : %7.1f KB  %s, Ethos-U fast scratch\r\n",
         (float)scratch_bytes / 1024.0f,
         model_mem_type_name(AvdkMultiModel::fastScratchType()));

    LOGI("[Result]\r\n");
    LOGI("  invokes %u, failures %u, invoke avg %.2f ms (min %.2f, max %.2f)\r\n",
         (unsigned)s_round_runs, (unsigned)s_round_failures,
         (float)invoke_avg_us / 1000.0f,
         (float)s_round_invoke_min_us / 1000.0f,
         (float)s_round_invoke_max_us / 1000.0f);
    LOGI("  arena used  : %7.1f KB / %7.1f KB (%.1f%%)\r\n",
         (float)arena_used / 1024.0f, (float)arena_capacity / 1024.0f,
         arena_capacity ? (100.0f * (float)arena_used / (float)arena_capacity) : 0.0f);
    LOGI("  VERDICT     : %s\r\n", pass ? "PASS" : "FAIL");
    LOGI("CSV,round=%d,invoke_us=%u,runs=%u/%u,pass=%d\r\n",
         round, (unsigned)invoke_avg_us, (unsigned)s_round_runs,
         (unsigned)MODEL_RUNS_PER_ROUND, pass ? 1 : 0);
    LOGI("=======================================================\r\n");
}

static void model_task(void *arg)
{
    (void)arg;

    AvdkMultiModel *model = new AvdkMultiModel();
    if (model == NULL)
    {
        LOGE("model alloc failed\r\n");
        return;
    }
    s_model = model;

    /* Flash -> PSRAM slab (uncoded), 1 MB arena in PSRAM, 448 KB fast scratch
     * in HSRAM - the same resource layout the datasheet test uses. */
    model->setName("mobilenet_v1");
    model->setModelType(AVDK_NN_MODEL_TYPE_NPU);
    model->setModelLoadType(AVDK_NN_MODEL_LOAD_TYPE_FLASH);
    model->setModelRamType(AVDK_NN_MEM_TYPE_PSRAM_SLAB_UNCODED);
    model->setArenaRam(AVDK_NN_MEM_TYPE_PSRAM_SLAB, MODEL_ARENA_SIZE);
    model->setFastRam(AVDK_NN_MEM_TYPE_HSRAM, MODEL_SCRATCH_SIZE);
    model->setFlashModel((uint8_t *)mobilenet_v1_1_0_224_quant_vela_tflite,
                         mobilenet_v1_1_0_224_quant_vela_tflite_len);

    if (model->init() != 0)
    {
        LOGE("model init failed\r\n");
        return;
    }

    if (model->prepareInterpreter() != 0)
    {
        LOGE("prepare interpreter failed (arena=%u bytes)\r\n",
             (unsigned)MODEL_ARENA_SIZE);
        return;
    }

    s_interpreter = model->interpreter();
    TfLiteTensor *input = s_interpreter->input(0);
    if (input == NULL || input->dims == NULL || input->dims->size != 4 ||
        input->dims->data[1] != MODEL_INPUT_H ||
        input->dims->data[2] != MODEL_INPUT_W ||
        input->dims->data[3] != MODEL_INPUT_C ||
        (uint32_t)input->bytes != (uint32_t)MODEL_INPUT_BYTES)
    {
        LOGE("input tensor mismatch, expect [1,%d,%d,%d] %d bytes\r\n",
             MODEL_INPUT_H, MODEL_INPUT_W, MODEL_INPUT_C, MODEL_INPUT_BYTES);
        return;
    }

    LOGI("\r\n");
    LOGI("================================================\r\n");
    LOGI("mobilenet_v1 benchmark: input %dx%dx%d, %d zero bytes per invoke\r\n",
         MODEL_INPUT_W, MODEL_INPUT_H, MODEL_INPUT_C, MODEL_INPUT_BYTES);
    LOGI("================================================\r\n");
    LOGI("\r\n");

    int round = 1;
    while (1)
    {
        model_round_stats_reset();

        LOGI("------------------------------------------------\r\n");
        LOGI("round %d: %d invokes on an all-zero input\r\n",
             round, MODEL_RUNS_PER_ROUND);

        for (int i = 0; i < MODEL_RUNS_PER_ROUND; i++)
        {
            uint64_t start_us;
            uint32_t invoke_us;
            TfLiteStatus status;

            /* Feed the same 224x224x3 all-zero image before every invoke, so the
             * measurement only covers Invoke() itself. */
            memset(input->data.raw, 0, MODEL_INPUT_BYTES);

            start_us = bk_aon_rtc_get_us();
            status = s_interpreter->Invoke();
            invoke_us = (uint32_t)(bk_aon_rtc_get_us() - start_us);

            if (status != kTfLiteOk)
            {
                LOGE("Invoke #%d failed\r\n", i + 1);
                s_round_failures++;
                continue;
            }

            s_round_invoke_sum_us += invoke_us;
            if (s_round_runs == 0 || invoke_us < s_round_invoke_min_us)
            {
                s_round_invoke_min_us = invoke_us;
            }
            if (invoke_us > s_round_invoke_max_us)
            {
                s_round_invoke_max_us = invoke_us;
            }
            s_round_runs++;

            LOGI("mobilenet_v1 Invoke #%d: %.2f ms\r\n",
                 i + 1, (float)invoke_us / 1000.0f);
        }

        LOGI("\r\n");
        LOGI("---------------- round %d done, next one in 5 seconds ----------------\r\n",
             round);
        LOGI("\r\n");

        model_print_round_report(round);

        round++;
        rtos_delay_milliseconds(5000);
    }
}

int main(void)
{
    bk_init();

    media_service_init();

#ifdef CONFIG_FRAME_BUFFER
    bk_frame_buffer_init();
#endif

    beken_thread_t thread = NULL;
    bk_err_t ret = rtos_create_thread(&thread,
                                      BEKEN_DEFAULT_WORKER_PRIORITY - 1,
                                      "model_task",
                                      (beken_thread_function_t)model_task,
                                      MODEL_TASK_STACK_SIZE,
                                      NULL);
    if (ret != BK_OK)
    {
        LOGE("create model task failed ret=%d\r\n", ret);
    }

    return 0;
}
